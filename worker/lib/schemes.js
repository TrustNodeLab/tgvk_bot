// Возвращает первую схему, которая нашлась в тексте (по приоритету списка).
export function detectScheme(text) {
  const src = String(text || "").toLowerCase();
  for (const s of SCHEMES) {
    for (const re of s.re) {
      if (re.test(src)) return s;
    }
  }
  return null;
}

// Простой выбор из массива шаблонов: стабильный по hash, чтобы соседние посты
// не повторяли дословно один и тот же заголовок/лид, но для одного текста был
// детерминированным (тесты не прыгают).
export function pickByHash(arr, seed, salt = "") {
  if (!arr || !arr.length) return "";
  const s = String(seed || "") + salt;
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return arr[h % arr.length];
}
